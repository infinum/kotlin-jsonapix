package com.infinum.jsonapix.processor.compile

import org.junit.jupiter.api.Assertions.fail

/**
 * APIs that only exist on the JVM. Generated code must not use them, because KMP consumers compile it
 * for iOS and the web too. Each pattern matches the name the failure message shows.
 * - `java.` and `javax.` match any qualified name, not just imports, because KotlinPoet writes a
 *   fully qualified name instead of an import when two simple names clash.
 * - `retrofit2` is allowed only in the import the Retrofit extension needs, see [isRetrofitExtensionImport].
 */
private val jvmOnlyApis = listOf(
    Regex("""(?<![\w.])javax?\.[\w.]+"""),
    Regex("""kotlin\.reflect\.full"""),
    Regex("""kotlin\.jvm\.internal"""),
    Regex("""::class\.java"""),
    Regex("""\.qualifiedName"""),
    Regex("""Class\.forName"""),
    Regex("""retrofit2"""),
)

private const val RETROFIT_EXTENSION_FILE = "com/infinum/jsonapix/JsonXCoreExtensions.kt"
private const val RETROFIT_EXTENSION_IMPORT = "import retrofit2.HttpException"

/**
 * Fails if any file in [generated] uses a JVM-only API, naming each file, line and API. This is a
 * cheap guard: only compiling and running the generated code on every target proves it is common-safe.
 */
internal fun assertNoJvmOnlyApis(fixture: Fixture, backend: Backend, generated: Map<String, String>) {
    val usages = generated.toSortedMap().flatMap { (path, text) ->
        text.lines().withIndex()
            .filterNot { (_, line) -> isRetrofitExtensionImport(path, line) }
            .flatMap { (index, line) ->
                jvmOnlyApis.mapNotNull { it.find(line) }
                    .map { "$backend/$fixture/$path:${index + 1} uses `${it.value}`: ${line.trim()}" }
            }
    }
    if (usages.isNotEmpty()) {
        fail<Unit>(
            "Sources generated by $backend for fixture '$fixture' use JVM-only APIs, " +
                "so they won't compile for iOS or the web.\n\n" +
                usages.joinToString("\n"),
        )
    }
}

/**
 * Whether [line] of the generated file at [path] is the import of Retrofit's `HttpException`. The
 * generated `HttpException.asJsonXHttpException()` needs it, and its body names no other Retrofit API.
 */
private fun isRetrofitExtensionImport(path: String, line: String): Boolean =
    path == RETROFIT_EXTENSION_FILE && line == RETROFIT_EXTENSION_IMPORT
