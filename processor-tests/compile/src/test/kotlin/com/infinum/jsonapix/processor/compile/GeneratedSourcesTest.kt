package com.infinum.jsonapix.processor.compile

import com.tschuchort.compiletesting.KotlinCompilation
import java.io.File
import java.io.OutputStream
import org.jetbrains.kotlinx.serialization.compiler.extensions.SerializationComponentRegistrar
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Assertions.fail
import org.junit.jupiter.api.io.TempDir
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.Arguments
import org.junit.jupiter.params.provider.MethodSource

/**
 * Compiles every fixture with every backend and compares the generated sources with the
 * checked-in golden files. Run with `-PupdateGoldens=true` to rewrite the golden files instead.
 */
internal class GeneratedSourcesTest {

    @ParameterizedTest(name = "{0} with {1}")
    @MethodSource("fixturesAndBackends")
    fun `generated sources compile and match the golden files`(
        fixture: Fixture,
        backend: Backend,
        @TempDir workingDir: File,
    ) {
        val generated = compile(fixture, backend, workingDir)
        assertTrue(generated.isNotEmpty()) { "$backend generated no files for fixture '$fixture'." }

        val goldens = GoldenFiles(CompileTestSettings.goldensDir.resolve(fixture.name))
        if (CompileTestSettings.updateGoldens) {
            goldens.write(generated)
            return
        }

        val differences = describeDifferences(
            golden = goldens.read(),
            generated = generated,
            goldenLabel = "golden/$fixture",
            generatedLabel = "$backend/$fixture",
        )
        if (differences.isNotEmpty()) {
            fail<Unit>(
                "Sources generated by $backend for fixture '$fixture' differ from its golden files. " +
                    "If the change is intended, rerun with -PupdateGoldens=true and review the golden diff.\n\n" +
                    differences.joinToString("\n\n"),
            )
        }
    }

    /** Compiles [fixture] with [backend] and returns the generated sources, keyed by relative path. */
    private fun compile(fixture: Fixture, backend: Backend, workingDir: File): Map<String, String> {
        val compilation = KotlinCompilation().apply {
            this.workingDir = workingDir
            sources = fixture.sources()
            inheritClassPath = true
            jvmTarget = "17"
            compilerPluginRegistrars = listOf(SerializationComponentRegistrar())
            messageOutputStream = OutputStream.nullOutputStream()
            backend.configure(this)
        }
        val result = compilation.compile()
        assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode) {
            "Fixture '$fixture' did not compile with $backend:\n${result.messages}"
        }
        return backend.generatedSourceDirs(compilation)
            .map(::readSourceTree)
            .fold(emptyMap()) { all, files -> all + files }
    }

    companion object {

        @JvmStatic
        fun fixturesAndBackends(): List<Arguments> =
            Fixture.all().flatMap { fixture ->
                Backend.entries.map { backend -> Arguments.of(fixture, backend) }
            }
    }
}
